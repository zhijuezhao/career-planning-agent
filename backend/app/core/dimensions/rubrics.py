"""六维评分标准的**唯一真相**（学生能力侧 / 岗位能力侧两套）。

为什么要单独一个模块
--------------------
2026-09-27 用户拍板：**人岗匹配 = 六维画像与其他方面的综合匹配**，所以两侧必须用
**同一套六维**（维度名必须逐字相同，否则 `job_matcher` 逐维对比时对不上）；
但**评分标准必须分侧**——一侧评"这个人有多强"（能力水平），另一侧评"这个岗位要求多高"
（要求强度）。同一个名字在两侧是**不同的尺**。

而在这之前，评分标准是**写死在两份提示词长文本里**的（学生侧在
`llm/prompts/resume_parsing.py`，岗位侧压根没有锚点）→ 想调一格分数描述就得改提示词，
没法迭代。用户明确要"**做好规划，方便我进行迭代升级**"，所以：

- **维度与子维度**：只在这里定义（`resume_agent.schemas` 从这里取，两侧提示词也用它渲染）；
- **两套 rubric**：`RUBRICS["candidate"]` / `RUBRICS["job"]`，**纯数据**，改它就是改标准；
- **版本号**：`RUBRIC_VERSION` 入库时记进画像/快照，便于"这批数据按哪版标准打的"可追溯；
- **渲染**：`render_rubric(side)` 把数据渲染成提示词里那段"评分标准"，提示词只写引用。

两侧的尺怎么分（用户第 2 点：子维同名，但细节**不许照搬**）
------------------------------------------------------------
- 学生侧：以**人**为对象，看"简历/经历里有没有证据、证据有多硬"；
- 岗位侧：以**岗位**为对象，看"门槛有多高、约束有多死"。

同一个子维度（例如「地域与薪资匹配」）在两侧的含义因此不同：
学生侧是"我的期望与岗位相容吗"，岗位侧是"这个岗位对地域与薪资的**约束强度**"。
逐条细节见下面 `RUBRICS`，每一格都可以直接改。
"""

