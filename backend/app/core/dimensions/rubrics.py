def side_label(side: str) -> str:
    return SIDE_LABELS.get(side, side)


def validate_rubrics() -> None:
    """结构自检：两侧必须覆盖**完全相同的**维度与子维度，且锚点 1–5 齐全。

    这是防"两侧漂移"的闸门：**维度名不一致 → 匹配对不上；子维不一致 → 迭代时漏改一侧**。
    导入时就跑（见文件末尾），定义写错会**立刻炸**，而不是等到线上匹配全错位。
    """
    expected_dims = set(DIMENSIONS)
    expected_subs = {dim: set(subs) for dim, subs in DIMENSIONS.items()}

    for side, dims in RUBRICS.items():
        if set(dims) != expected_dims:
            raise RuntimeError(
                f"rubric[{side}] 维度不匹配：多了 {sorted(set(dims) - expected_dims)}、"
                f"少了 {sorted(expected_dims - set(dims))}"
            )
        for dim, spec in dims.items():
            subs = spec.get("sub_dimensions") or {}
            if set(subs) != expected_subs[dim]:
                raise RuntimeError(
                    f"rubric[{side}][{dim}] 子维度不匹配：多了 "
                    f"{sorted(set(subs) - expected_subs[dim])}、"
                    f"少了 {sorted(expected_subs[dim] - set(subs))}"
                )
            anchors = spec.get("anchors") or {}
            if set(anchors) != {1, 2, 3, 4, 5}:
                raise RuntimeError(f"rubric[{side}][{dim}] 锚点必须齐全 1–5，实为 {sorted(anchors)}")
            if not (spec.get("focus") or "").strip():
                raise RuntimeError(f"rubric[{side}][{dim}] 缺 focus")


validate_rubrics()


def render_rubric(side: str) -> str:
    """把某一侧的 rubric 渲染成**提示词里那段评分标准**。

    提示词只写 `{render_rubric("candidate")}` —— 改标准只改上面的数据。
    """
    if side not in RUBRICS:
        raise KeyError(f"未知的评分侧：{side!r}（可选 {sorted(RUBRICS)}）")

    levels = LEVEL_MEANING[side]
    lines: list[str] = [
        f"### 评分标准（{side_label(side)}，1–5 分制）",
        "",
        "**总纲（同一把尺，但描述对象是"
        + ("这个人" if side == "candidate" else "这个岗位")
        + "）**",
    ]
    for level in (1, 2, 3, 4, 5):
        lines.append(f"- {level} 分 = {levels[level]}")

    lines += [
        "",
        "**逐维标准**（每个顶层维度的分数 = 其子维度的等权平均）",
    ]
    for dim in DIMENSION_ORDER:
        spec = RUBRICS[side][dim]
        lines += [
            "",
            f"■ {dim}",
            f"  · 看什么：{spec['focus']}",
            "  · 分数锚点：",
        ]
        for level in (1, 2, 3, 4, 5):
            lines.append(f"    - {level} 分：{spec['anchors'][level]}")
        lines.append("  · 子维度（各自独立给 1–5 分）：")
        for sub in DIMENSIONS[dim]:
            lines.append(f"    - {sub}：{spec['sub_dimensions'][sub]}")

    return "\n".join(lines)


